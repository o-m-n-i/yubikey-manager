package piv

import (
	"context"
	"crypto/sha256"
	"crypto/x509"
	"encoding/pem"
	"errors"
	"fmt"
	"strings"

	"github.com/bobbydams/yubikey-manager/internal/executor"
)

// Ykman runs the ykman commands behind `ykgpg piv`. Every call is pinned to a
// serial with --device, and none carries a PIN, PUK or management key:
// anything that needs one runs interactively so ykman asks on the terminal.
type Ykman struct {
	exec executor.Executor
}

// NewYkman returns a Ykman backed by the given executor.
func NewYkman(exec executor.Executor) *Ykman {
	return &Ykman{exec: exec}
}

// Serials lists the serial numbers of all connected YubiKeys.
func (y *Ykman) Serials(ctx context.Context) ([]string, error) {
	out, err := y.exec.Run(ctx, "ykman", "list", "--serials")
	if err != nil {
		return nil, fmt.Errorf("listing YubiKeys with ykman (brew install ykman): %w", err)
	}
	var serials []string
	for _, line := range strings.Split(string(out), "\n") {
		if s := strings.TrimSpace(line); s != "" {
			serials = append(serials, s)
		}
	}
	return serials, nil
}

// Info reads the PIV state. `ykman piv info` reports default credentials
// without spending a PIN, PUK or management key attempt.
func (y *Ykman) Info(ctx context.Context, serial string) (*Info, error) {
	out, err := y.exec.Run(ctx, "ykman", "--device", serial, "piv", "info")
	if err != nil {
		return nil, fmt.Errorf("ykman piv info: %w", err)
	}
	return ParseInfo(string(out))
}

// KeyPolicy reads the PIN/touch policy of the key in a slot.
func (y *Ykman) KeyPolicy(ctx context.Context, serial, slot string) (*KeyPolicy, error) {
	out, err := y.exec.Run(ctx, "ykman", "--device", serial, "piv", "keys", "info", slot)
	if err != nil {
		return nil, fmt.Errorf("ykman piv keys info %s: %w", slot, err)
	}
	return ParseKeyInfo(string(out))
}

// Certificate exports the certificate in a slot (public data only).
func (y *Ykman) Certificate(ctx context.Context, serial, slot string) (*x509.Certificate, error) {
	out, err := y.exec.Run(ctx, "ykman", "--device", serial, "piv", "certificates", "export", slot, "-")
	if err != nil {
		return nil, fmt.Errorf("exporting the certificate in slot %s: %w", slot, err)
	}
	certs, err := ParseCertificatesPEM(out)
	if err != nil {
		return nil, err
	}
	return certs[0], nil
}

// GenerateKey creates an ECCP256 key in slot 9a (PIN once, touch always) and
// writes its public half to pubPath. ykman asks for the management key.
func (y *Ykman) GenerateKey(ctx context.Context, serial, pubPath string) error {
	return y.exec.RunInteractive(ctx, "ykman", "--device", serial, "piv", "keys", "generate",
		"-a", "ECCP256", "--pin-policy", "ONCE", "--touch-policy", "ALWAYS", SlotAuth, pubPath)
}

// GenerateCertificate writes a self-signed certificate for the key in slot 9a.
// ykman asks for the PIV PIN and the management key, and the key wants a touch.
func (y *Ykman) GenerateCertificate(ctx context.Context, serial, subject string, days int, pubPath string) error {
	return y.exec.RunInteractive(ctx, "ykman", "--device", serial, "piv", "certificates", "generate",
		"-s", subject, "-d", fmt.Sprint(days), SlotAuth, pubPath)
}

// ChangePIN replaces the PIV PIN; ykman prompts for the old and new PIN.
func (y *Ykman) ChangePIN(ctx context.Context, serial string) error {
	return y.exec.RunInteractive(ctx, "ykman", "--device", serial, "piv", "access", "change-pin")
}

// ChangePUK replaces the PIV PUK; ykman prompts for the old and new PUK.
func (y *Ykman) ChangePUK(ctx context.Context, serial string) error {
	return y.exec.RunInteractive(ctx, "ykman", "--device", serial, "piv", "access", "change-puk")
}

// ProtectManagementKey sets a random AES192 management key that is stored on
// the YubiKey, protected by the PIV PIN. The key is generated by ykman and is
// never shown.
func (y *Ykman) ProtectManagementKey(ctx context.Context, serial string) error {
	return y.exec.RunInteractive(ctx, "ykman", "--device", serial, "piv", "access", "change-management-key",
		"-a", "AES192", "--generate", "--protect")
}

// ParseCertificatesPEM decodes every CERTIFICATE block in data.
func ParseCertificatesPEM(data []byte) ([]*x509.Certificate, error) {
	var certs []*x509.Certificate
	rest := data
	for {
		var block *pem.Block
		block, rest = pem.Decode(rest)
		if block == nil {
			break
		}
		if block.Type != "CERTIFICATE" {
			continue
		}
		c, err := x509.ParseCertificate(block.Bytes)
		if err != nil {
			return nil, fmt.Errorf("parsing certificate: %w", err)
		}
		certs = append(certs, c)
	}
	if len(certs) == 0 {
		return nil, errors.New("no certificate found in PEM data")
	}
	return certs, nil
}

// Fingerprint is the SHA-256 of the certificate's DER encoding as lower-case
// hex, the form used to compare a YubiKey certificate with Vault's roles.
func Fingerprint(c *x509.Certificate) string {
	sum := sha256.Sum256(c.Raw)
	return fmt.Sprintf("%x", sum)
}

// FormatFingerprint renders a fingerprint as colon-separated upper-case pairs.
func FormatFingerprint(fp string) string {
	fp = strings.ToUpper(fp)
	var parts []string
	for i := 0; i+2 <= len(fp); i += 2 {
		parts = append(parts, fp[i:i+2])
	}
	return strings.Join(parts, ":")
}
